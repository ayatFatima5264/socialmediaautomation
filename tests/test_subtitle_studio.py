    """A real 3-second WAV, generated by ffmpeg rather than hand-assembled.

    Used wherever the pipeline has to decode something: `probe_bytes` reads its
    duration, `extract_audio` re-encodes it, and both would reject a
    hand-written header. A tone is enough — the speech model is substituted, so
    what matters is that the *file* is genuine.
    """
    result = subprocess.run(
        [
            ffmpeg_path(), "-hide_banner", "-loglevel", "error", "-y",
            "-f", "lavfi", "-i", "sine=frequency=440:duration=3",
            "-ac", "1", "-ar", "16000",
            "-f", "wav", "pipe:1",
        ],
        capture_output=True,
        timeout=120,
    )
    if result.returncode != 0 or not result.stdout:
        pytest.skip("ffmpeg could not generate test audio")
    return result.stdout


