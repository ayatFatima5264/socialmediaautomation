def test_exporting_writes_the_file_to_object_storage(client):
    """A subtitle file is small, but "small files may go in the database" is
    the exception that grows until the rule is meaningless."""
    headers = auth(client)
    cues = real_cues()

    stored = client.post(
        "/api/video/subtitles/export",
        headers=headers,
        json={"cues": cues, "format": "srt", "title": "Autumn menu"},
    )

    assert stored.status_code == 201
    body = stored.json()
    assert body["format"] == "srt"
    assert body["cue_count"] == len(cues)
    assert "/api/storage/o/" in body["url"]

    db = next(app.dependency_overrides[get_db]())
    asset = db.query(VideoAsset).filter_by(kind="subtitle").one()
    obj = db.query(StorageObject).filter_by(key=asset.storage_key).one()
    db.close()

    # The row keeps a key; the bytes are in the store.
    assert asset.storage_key.endswith(".srt")
    assert obj.data.decode("utf-8").startswith("1\n")


