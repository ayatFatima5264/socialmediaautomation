def test_srt_round_trips_through_the_parser():
    cues = real_cues()

    srt, content_type, extension = transcription_service.render(cues, "srt")
    reparsed = engine.parse(srt)

    assert (content_type, extension) == ("application/x-subrip", "srt")
    assert len(reparsed) == len(cues)
    for original, parsed in zip(cues, reparsed):
        assert parsed["text"] == original["text"]
        assert parsed["start"] == pytest.approx(original["start"], abs=0.01)
        assert parsed["end"] == pytest.approx(original["end"], abs=0.01)


def test_vtt_round_trips_and_carries_its_header():
    cues = real_cues()

    vtt, content_type, _ = transcription_service.render(cues, "vtt")

    assert vtt.startswith("WEBVTT")
    assert content_type == "text/vtt"
    # WebVTT uses a dot before the milliseconds; SRT uses a comma. Getting this
    # wrong produces a file players silently ignore.
    assert "." in vtt.split("-->")[0].split("\n")[-1]
    assert len(engine.parse(vtt)) == len(cues)


def test_txt_is_the_words_with_no_timings():
    cues = real_cues()

    txt, content_type, _ = transcription_service.render(cues, "txt")

    assert content_type == "text/plain"
    assert "-->" not in txt
    for cue in cues:
        assert cue["text"].replace("\n", " ") in txt.replace("\n", " ")


