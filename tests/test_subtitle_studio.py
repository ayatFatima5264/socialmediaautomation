class FakeWhisper(TranscriptionProvider):
    """Returns a real Transcript shape; records what it was handed.

    Substituting here rather than higher up is what makes the rest of the
    pipeline genuinely under test: the audio really is extracted by ffmpeg, the
    cues really are built by `cues_from_transcript`, and the only thing that
    does not happen is the HTTP request.
    """

    name = "fake-whisper"

    def __init__(self, *, fail_with: Exception | None = None) -> None:
        self.fail_with = fail_with
        self.calls: list[dict] = []

    async def transcribe(
        self, *, audio, filename, content_type, language=None,
        word_timestamps=True, translate_to_english=False,
    ) -> Transcript:
        self.calls.append(
            {
                "bytes": len(audio),
                "filename": filename,
                "content_type": content_type,
                "language": language,
                "translate": translate_to_english,
            }
        )
        if self.fail_with is not None:
            raise self.fail_with

        return Transcript(
            text=SCRIPT,
            language="English",
            duration_seconds=9.5,
            segments=[
                TranscriptSegment(0.0, 3.0, "Autumn is here, and so is our new seasonal menu."),
                TranscriptSegment(3.2, 6.4, "Come in for spiced apple cake and a flat white."),
                TranscriptSegment(6.6, 9.5, "We are open until six every day this week."),
            ],
            words=[TranscriptWord(0.0, 0.4, "Autumn"), TranscriptWord(0.4, 0.6, "is")],
            provider=self.name,
            model="fake-large-v3",
        )


