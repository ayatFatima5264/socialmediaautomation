def test_a_script_is_timed_into_readable_cues():
    cues = real_cues(duration=12.0)

    assert engine.total_duration(cues) == pytest.approx(12.0, abs=0.01)
    # Every cue is inside the reading limits the style asks for.
    for cue in cues:
        assert cue["end"] > cue["start"]
        for line in cue["text"].split("\n"):
            assert len(line) <= engine.DEFAULT_MAX_CHARS_PER_LINE
        assert len(cue["text"].split("\n")) <= engine.DEFAULT_MAX_LINES


def test_script_timing_apportions_by_length_not_evenly():
    """"OK." and a 30-word clause are not the same length of speech."""
    cues = engine.cues_from_script(
        "Hi. " + ("A rather much longer sentence that keeps going for a while. "),
        duration_seconds=10,
    )
    assert len(cues) >= 2
    first = cues[0]["end"] - cues[0]["start"]
    second = cues[1]["end"] - cues[1]["start"]
    assert second > first


def test_a_transcript_becomes_cues_split_on_reading_limits(provider):
    """A speech model returns whatever segment length it felt like; that is not
    a subtitle. This is the step that makes it one."""
    import asyncio

    transcript = asyncio.run(
        provider.transcribe(audio=b"x", filename="a.wav", content_type="audio/wav")
    )
    cues = engine.cues_from_transcript(transcript)

    assert len(cues) >= len(transcript.segments)
    for cue in cues:
        for line in cue["text"].split("\n"):
            assert len(line) <= engine.DEFAULT_MAX_CHARS_PER_LINE


def test_normalize_removes_overlaps_and_orders_the_track():
    messy = [
        {"start": 5.0, "end": 7.0, "text": "second"},
        {"start": 0.0, "end": 6.0, "text": "first, overlapping"},
    ]

    cleaned = engine.normalize(messy)

    assert [c["text"] for c in cleaned] == ["first, overlapping", "second"]
    assert cleaned[0]["end"] <= cleaned[1]["start"]


