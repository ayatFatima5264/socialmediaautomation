def test_inserting_lands_in_the_position_asked_for():
    """A contiguous track has no gap, so the insert has to make room — and if
    it silently reordered instead, this is what would catch it."""
    cues = real_cues()

    added = engine.insert_cue(cues, index=0, text="Inserted line")

    assert added[1]["text"] == "Inserted line"
    assert added[0]["text"] == cues[0]["text"]
    assert added[1]["start"] >= added[0]["end"]
    assert added[2]["start"] >= added[1]["end"]


