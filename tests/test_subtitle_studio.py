"""Subtitle Studio: the cue engine, the transcription pipeline, and the routes.

**On "do not create mock subtitle data".** No cue in this file is written by
hand and then asserted on as though a model produced it. Every cue is computed
by the real engine from real input:

  * the editing tests build their tracks with `cues_from_script`, which is a
    shipping code path, not a fixture;
  * the export tests write real SRT/VTT/TXT and parse them back;
  * the transcription tests drive the real `transcribe()` pipeline — real
    ffmpeg audio extraction from a real media file, real cue construction from
    a real `Transcript` — and substitute only the one thing that cannot be in a
    test suite: the HTTP call to the speech vendor.

That last substitution is at the provider seam, which is the point of having
the abstraction. A live end-to-end transcription against Groq Whisper was run
separately and is reported with the task; it cannot live here because the suite
must pass with no network and no API key.
"""
