def real_cues(duration: float = 12.0) -> list[dict]:
    """A track built by the shipping script-timing path, not typed by hand."""
    cues = engine.cues_from_script(SCRIPT, duration_seconds=duration)
    assert len(cues) >= 3, "the fixture script should produce several cues"
    return cues


